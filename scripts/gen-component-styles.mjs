#!/usr/bin/env node
// gen-component-styles.mjs — emit the component-only public CSS entry
// (BJ.W4-TYPEDSEAM).
// ============================================================================
// `@mkbabb/glass-ui/styles.css` is the SFC-only public entry (component paint
// WITHOUT the token/global cascade). The raw SFC bundle `dist/glass-ui.css`
// emits the `.glass-track-well` / `.glass-value-marks` / `.glass-value-mark`
// classes but carries ZERO rules for that SHARED W4 structure — those live in
// the `@layer components` partials that only the canonical `/styles` cascade
// folds. So an installed consumer importing `/styles.css` lost the recessed
// groove (position/overflow/pill radius) and every mark dot.
//
// This generates `dist/component-styles.css`: a packed manifest that imports the
// two required W4 partials ONCE, in order, BEFORE the unlayered SFC rules —
//     @import "./styles/glass/track-well.css";
//     @import "./styles/glass/value-marks.css";
//     @import "./glass-ui.css";
// The canonical `/styles` (`dist/styles/index.css`) is UNCHANGED and does NOT
// import this manifest, so the full cascade has no duplicate W4 definition; a
// consumer needs exactly ONE public style entry.
//
// Paths are relative to `dist/`. The three targets must exist post-build; a
// missing target is a HARD ERROR (fail-closed — never ship a manifest that
// imports a phantom).
// ============================================================================

import { existsSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const DIST = resolve(REPO_ROOT, "dist");

// The exact ordered manifest members (relative to dist/).
const MEMBERS = [
    "./styles/glass/track-well.css",
    "./styles/glass/value-marks.css",
    "./glass-ui.css",
];

const missing = MEMBERS.filter((m) => !existsSync(resolve(DIST, m)));
if (missing.length) {
    console.error(
        `gen-component-styles: ${missing.length} manifest target(s) absent from dist/ — ${missing.join(", ")}. Run \`vite build\` first.`,
    );
    process.exit(1);
}

const banner =
    "/* GENERATED by scripts/gen-component-styles.mjs — the component-only\n" +
    "   `@mkbabb/glass-ui/styles.css` entry: the shared W4 track-well + value-marks\n" +
    "   structure folded ONCE before the raw SFC bundle. Do not edit by hand. */\n";

const body = MEMBERS.map((m) => `@import "${m}";`).join("\n") + "\n";

writeFileSync(resolve(DIST, "component-styles.css"), banner + body, "utf8");
console.log("gen-component-styles: wrote dist/component-styles.css");
