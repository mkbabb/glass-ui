import { chromium } from "playwright";
import { PNG } from "pngjs";
const OUT = new URL(".", import.meta.url).pathname;
const b = await chromium.connectOverCDP("http://localhost:9333");
const ctx = b.contexts()[0] || await b.newContext();
const page = await ctx.newPage();
await page.emulateMedia({ reducedMotion: "reduce" });
await page.setViewportSize({ width: 1440, height: 1200 });
await page.goto("http://localhost:5200/substrates/blob", { waitUntil: "load", timeout: 30000 });
await page.waitForTimeout(3500);
await page.evaluate(() => document.querySelector(".goo-blob-canvas").scrollIntoView({block:"center"}));
await page.waitForTimeout(1000);
const canv = await page.evaluate(() => { const b=document.querySelector(".goo-blob-canvas").getBoundingClientRect(); return {x:b.x,y:b.y,w:b.width,h:b.height,vh:innerHeight,vw:innerWidth}; });
const clip = { x: Math.max(0,Math.round(canv.x)), y: Math.max(0,Math.round(canv.y)), width: Math.min(canv.vw,Math.round(canv.x+canv.w))-Math.max(0,Math.round(canv.x)), height: Math.min(canv.vh,Math.round(canv.y+canv.h))-Math.max(0,Math.round(canv.y)) };
const shot = async () => await page.screenshot({ clip });
const mad=(a,b)=>{const pa=PNG.sync.read(a),pb=PNG.sync.read(b);const n=Math.min(pa.data.length,pb.data.length);let s=0,c=0;for(let i=0;i<n;i+=4){s+=Math.abs(pa.data[i]-pb.data[i])+Math.abs(pa.data[i+1]-pb.data[i+1])+Math.abs(pa.data[i+2]-pb.data[i+2]);c+=3;}return s/c;};
await page.mouse.move(20,20); await page.waitForTimeout(500);
const a=await shot(); await page.waitForTimeout(250); const b2=await shot(); await page.waitForTimeout(250); const c2=await shot();
await page.screenshot({clip, path: OUT+"prm-rest.png"});
const d1=mad(a,b2), d2=mad(b2,c2);
console.log(JSON.stringify({ prmReducedMotion: true, restDeltas:[+d1.toFixed(3),+d2.toFixed(3)], note:"under PRM the loop parks; deltas should be ~0 (static seat)" }, null, 2));
await page.close(); await b.close();
