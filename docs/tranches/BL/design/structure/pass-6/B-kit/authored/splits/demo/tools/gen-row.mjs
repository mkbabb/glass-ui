#!/usr/bin/env node
// gen-row.mjs — AUTHOR-SIDE: write the B-S11 zone-demo rows (../NN-<name>.mjs) as authored
// inputs to pass-4's derive/edits.mjs, from the tree before the splits and the tree after.
//
//   node gen-row.mjs --before <snapshot dir> --root <worktree> [--out <dir>]
//
// --out (default: the rows directory) takes a second arm's rows, e.g. arm-f/.
//
// rows.json names each row's files and each file's why. Every file that differs between
// the two trees in the demo, tests and tests-visual zones must be claimed by exactly one
// row, and every claimed file must differ, or the run stops before writing. A new file is
// { file, create }; a changed file is one { file, from, to } per hunk, from pass-4's
// lib/row.mjs hunksOf (each `from` widened with context until it is unique in the file).
// apply.mjs then re-applies the rows to a copy of the before tree and checks the after
// tree byte for byte.
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROWS = resolve(HERE, "..");
const KIT4 = resolve(HERE, "../../../../../../pass-4/B-kit");
const { hunksOf } = await import(pathToFileURL(join(KIT4, "lib/row.mjs")).href);

const args = process.argv.slice(2);
const arg = (k) => {
    const i = args.indexOf(k);
    if (i < 0) throw new Error(`missing ${k}`);
    return args[i + 1];
};
const before = resolve(arg("--before"));
const root = resolve(arg("--root"));
const OUT = args.includes("--out") ? resolve(arg("--out")) : ROWS;
const ZONES = ["demo", "tests", "tests-visual"];
const SKIP = new Set(["node_modules", "dist", "dist-demo", ".cache", "test-results", "playwright-report"]);

function walk(base, dir, acc) {
    if (!existsSync(dir)) return acc;
    for (const name of readdirSync(dir)) {
        if (SKIP.has(name)) continue;
        const abs = join(dir, name);
        const st = statSync(abs, { throwIfNoEntry: false });
        if (!st) continue;
        if (st.isDirectory()) walk(base, abs, acc);
        else acc.add(relative(base, abs));
    }
    return acc;
}
const A = new Set(), B = new Set();
for (const z of ZONES) {
    walk(before, join(before, z), A);
    walk(root, join(root, z), B);
}
const read = (base, set, f) => (set.has(f) ? readFileSync(join(base, f), "utf8") : null);
const changed = [...new Set([...A, ...B])].sort().filter((f) => read(before, A, f) !== read(root, B, f));

const spec = JSON.parse(readFileSync(join(ROWS, "rows.json"), "utf8"));
const claimed = new Map();
const stop = [];
for (const row of spec.rows) {
    for (const f of Object.keys(row.files)) {
        if (claimed.has(f)) stop.push(`${f}: claimed by ${claimed.get(f)} and ${row.id}`);
        claimed.set(f, row.id);
    }
}
for (const f of changed) if (!claimed.has(f)) stop.push(`${f}: changed, claimed by no row`);
for (const [f, id] of claimed) if (!changed.includes(f)) stop.push(`${f}: claimed by ${id}, unchanged`);
if (stop.length) {
    console.error(`stopped\n  ${stop.join("\n  ")}`);
    process.exit(1);
}

const summary = [];
for (const row of spec.rows) {
    const edits = [];
    for (const [f, why] of Object.entries(row.files)) {
        const a = read(before, A, f), b = read(root, B, f);
        if (a === null) edits.push({ file: f, why, create: b });
        else if (b === null) edits.push({ file: f, why, remove: true });
        else for (const [from, to] of hunksOf(a, b)) edits.push({ file: f, why, from, to });
    }
    const out = join(OUT, `${row.id}.mjs`);
    writeFileSync(
        out,
        `// ${row.id}.mjs — AUTHORED input to pass-4's derive/edits.mjs (B-S11, zone demo).
// Generated by tools/gen-row.mjs from the tree before and after the split (rows.json);
// every edit carries its own why. Made by ${row.author}.
export const why = ${JSON.stringify(row.why)};

export const edits = ${JSON.stringify(edits, null, 1)};
`,
    );
    const t = { create: 0, hunk: 0, remove: 0 };
    for (const e of edits) t[e.create !== undefined ? "create" : e.remove ? "remove" : "hunk"]++;
    summary.push({ row: row.id, files: Object.keys(row.files).length, ...t });
}
console.log(JSON.stringify({ changed: changed.length, rows: summary }, null, 1));
