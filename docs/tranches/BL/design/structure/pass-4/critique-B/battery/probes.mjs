// probes.mjs --root <tree> [--out <json>] · gate-independent measurements on a tree, one per checklist item that a
// file-system reading can fail. Written and hashed before reading the pass-4 kit. Prints `PROBE <id> <item> <PASS|FAIL|INFO> …`.
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from "node:fs";
import { join, resolve, dirname, basename, extname } from "node:path";

const arg = (k, d) => { const i = process.argv.indexOf(k); return i > 0 ? process.argv[i + 1] : d; };
const root = resolve(arg("--root"));
const ZONES = ["src", "demo", "scripts", "tests", "tests-visual"];
const SLOTS = new Set(["composables", "__tests__", "styles"]);
const SKIPD = new Set(["node_modules", ".git", "dist", "dist-demo", "test-results", "playwright-report", ".cache"]);
const CODE = new Set([".ts", ".mts", ".vue", ".mjs", ".js", ".css", ".cjs"]);
const files = [];
const dirsAll = [];
for (const z of ZONES) (function walk(d) {
    if (!existsSync(join(root, d))) return;
    dirsAll.push(d);
    for (const e of readdirSync(join(root, d), { withFileTypes: true })) {
        if (SKIPD.has(e.name) || e.isSymbolicLink()) continue;
        const p = `${d}/${e.name}`;
        if (e.isDirectory()) walk(p); else files.push(p);
    }
})(z);
const text = (p) => readFileSync(join(root, p), "utf8");
const lines = (p) => text(p).split("\n").length - (text(p).endsWith("\n") ? 1 : 0);
const generated = (p) => /\.d\.ts$|\.generated\.|\/generated\//.test(p) || /^\s*\/\/[^\n]*(GENERATED|generated by)/.test(text(p).slice(0, 400));
const out = [];
const probe = (id, item, verdict, detail) => { out.push({ id, item, verdict, detail }); console.log(`PROBE ${id} ${item} ${verdict} ${typeof detail === "string" ? detail : JSON.stringify(detail)}`); };

// ---- bounds (R-5, P3-R3) ----
const direct = (d) => files.filter((f) => dirname(f) === d);
const over12 = [], slotOver12 = [];
for (const d of dirsAll) {
    const n = direct(d).length;
    if (n > 12) (SLOTS.has(basename(d)) ? slotOver12 : over12).push(`${d}:${n}`);
}
const long = files.filter((f) => CODE.has(extname(f)) && !generated(f) && lines(f) > 500).map((f) => `${f}:${lines(f)}`);
const longSlot = long.filter((x) => x.split("/").some((s) => SLOTS.has(s)));
probe("PR-B12", "B-01/B-10 (R-5 12)", over12.length ? "FAIL" : "PASS", { count: over12.length, dirs: over12 });
probe("PR-SLOT", "S-03 (P3-R3)", slotOver12.length ? "FAIL" : "PASS", { count: slotOver12.length, dirs: slotOver12 });
probe("PR-500", "B-10 (B-S11)", long.length ? "FAIL" : "PASS", { count: long.length, slotFiles: longSlot.length, files: long });
const dockTests = files.filter((f) => /\/dock\/__tests__\/[^/]+$/.test(f)).length;
probe("PR-DOCKT", "S-03 (P3-R3 dock)", dockTests > 12 ? "FAIL" : "PASS", `dock/__tests__ direct files ${dockTests}`);
const tv = direct("tests-visual").length;
probe("PR-TV", "B-10 (B-S16)", tv > 12 ? "FAIL" : "PASS", `tests-visual direct files ${tv}`);

// ---- placements named by the checklist ----
const where = (b) => files.filter((f) => basename(f) === b);
const accent = where("accent-tone.css");
probe("PR-ACCENT", "B-08", accent.length === 1 && accent[0].startsWith("src/styles/") ? "PASS" : "FAIL", accent);
const safari = where("safari-probe.mjs");
probe("PR-SAFARI", "B-10 (B-S15)", safari.length === 1 && safari[0].split("/").length > 2 ? "PASS" : "FAIL", safari);
probe("PR-TELE", "S-03 (P3-R6)", "INFO", where("isTeleportedTarget.ts"));
const ue = where("vite.utility-emit.ts").concat(existsSync(join(root, "vite.utility-emit.ts")) ? ["vite.utility-emit.ts"] : []);
for (const u of ue) {
    const t = text(u);
    const silent = [...t.matchAll(/if\s*\(\s*!\s*existsSync\([^)]*\)\s*\)\s*(\{\s*)?return\b/g)].length;
    probe("PR-UEMIT", "S-14", silent ? "FAIL" : (/throw\s+new\s+Error/.test(t) ? "PASS" : "INFO"), `${u}: silent-return-on-missing ${silent}, throws ${(t.match(/throw\s+new\s+Error/g) || []).length}`);
}
// masking forms present in the tree today (live code, tests excluded)
const maskHits = [];
for (const f of files) {
    if (!/\.(ts|mts|mjs|js|vue)$/.test(f) || /__tests__|\.test\.|\.spec\./.test(f)) continue;
    const t = text(f);
    const n1 = (t.match(/\.catch\(\s*\(\s*\)\s*=>\s*(null|undefined|\{\s*\})\s*\)/g) || []).length;
    const n2 = (t.match(/if\s*\(\s*!\s*(fs\.)?existsSync\([^)]*\)\s*\)\s*(\{\s*)?return\s*(null|undefined|;|\})/g) || []).length;
    if (n1 + n2) maskHits.push(`${f}:catch=${n1},ret=${n2}`);
}
probe("PR-MASK", "S-14", "INFO", { count: maskHits.length, files: maskHits });

// ---- names (B-07): placeholder segments in every zone ----
const PH = /^(utils?|misc|helpers?|common|stuff|shared\d|v\d+|part-?\d+|new|old|tmp|temp|legacy|use)$/i;
const badDirs = dirsAll.filter((d) => d.split("/").slice(1).some((s) => PH.test(s)));
const badFiles = files.filter((f) => PH.test(basename(f).replace(/\.[^.]+$/, "")) || /-\d+\.[a-z]+$|\.legacy\./.test(basename(f)));
probe("PR-NAMES", "B-07", badDirs.length + badFiles.length ? "FAIL" : "PASS", { dirs: badDirs, files: badFiles });

// ---- surface (shared bar): export keys, typesVersions, ./aurora-config ----
const pkg = JSON.parse(text("package.json"));
const keys = Object.keys(pkg.exports || {});
const tvn = Object.keys((pkg.typesVersions || {})["*"] || {}).length;
probe("PR-KEYS", "S-03 (P3-R5)/shared bar", keys.includes("./aurora-config") ? "PASS" : "FAIL", `export keys ${keys.length}, typesVersions ${tvn}, ./aurora-config ${keys.includes("./aurora-config")}`);
probe("PR-TEST", "B-11", "INFO", `npm test = ${pkg.scripts?.test}`);

// ---- door cost (§P3-4): door files in module dirs, by class ----
const compDir = new Set(files.filter((f) => f.endsWith(".vue")).map((f) => dirname(f)));
const ancestorComp = (d) => { let p = dirname(d); while (p && p !== "." && p.includes("/")) { if (compDir.has(p)) return true; p = dirname(p); } return compDir.has(p); };
const descendantComp = (d) => [...compDir].some((c) => c.startsWith(d + "/"));
const doors = files.filter((f) => /\/index\.(ts|css)$/.test(f) && !f.includes("__tests__"));
const cls = (f) => {
    const d = dirname(f);
    if (f.startsWith("scripts/")) return "scripts";
    if (!f.startsWith("src/")) return "other-zone";
    if (ancestorComp(d)) return "nested";
    if (compDir.has(d)) return "unit-root";
    if (descendantComp(d) || d === "src" || /^src\/components$/.test(d)) return "aggregator";
    return "kernel";
};
const stm = (t) => t.replace(/\/\*[\s\S]*?\*\//g, "").split(/;|\n/).map((s) => s.trim()).filter((s) => s && !s.startsWith("//")).length;
const cost = {};
for (const f of doors) {
    const c = cls(f); const t = text(f);
    cost[c] ??= { doors: 0, bytes: 0, statements: 0, oneStatement: 0 };
    const s = stm(t);
    cost[c].doors++; cost[c].bytes += Buffer.byteLength(t); cost[c].statements += s; if (s === 1) cost[c].oneStatement++;
}
const tot = Object.values(cost).reduce((a, c) => ({ doors: a.doors + c.doors, bytes: a.bytes + c.bytes, statements: a.statements + c.statements, oneStatement: a.oneStatement + c.oneStatement }), { doors: 0, bytes: 0, statements: 0, oneStatement: 0 });
probe("PR-DOORS", "B-12 (§P3-4)", "INFO", { total: tot, byClass: cost });
// module dirs without a door (a code dir holding source but no index)
const codeDirs = [...new Set(files.filter((f) => f.startsWith("src/") && /\.(ts|vue)$/.test(f) && !f.includes("__tests__")).map((f) => dirname(f)))];
const doorless = codeDirs.filter((d) => !SLOTS.has(basename(d)) && !existsSync(join(root, d, "index.ts")) && !existsSync(join(root, d, "index.css")));
probe("PR-DOORLESS", "B-01 (B7)", doorless.length ? "FAIL" : "PASS", { count: doorless.length, dirs: doorless.slice(0, 40) });

// ---- counts (B-13) ----
probe("PR-COUNT", "B-13", "INFO", `zone files ${files.length}; by zone ${JSON.stringify(Object.fromEntries(ZONES.map((z) => [z, files.filter((f) => f.startsWith(z + "/")).length])))}`);
if (arg("--out")) writeFileSync(arg("--out"), JSON.stringify(out, null, 1));
