#!/usr/bin/env node
// gen-row.mjs — AUTHOR-SIDE: write one B-S11 split row (zone src) as an authored input to
// pass-4's derive/edits.mjs, from the tree before the split and the tree after it.
//
//   node gen-row.mjs --before <snapshot dir> --root <worktree> --out <row.mjs>
//                    --why "<row why>" --reasons <reasons.json>
//
// Every file that differs between the two trees (node_modules, dist, dist-demo, .git and the
// root docs/ excluded) becomes edits in derive/edits.mjs's vocabulary:
//   a new file     → { file, create }
//   a removed file → { file, remove: true }
//   a changed file → one { file, from, to } per hunk, from pass-4's lib/row.mjs hunksOf
//                    (each `from` widened with context until it is unique in the file)
// `reasons.json` maps a file path to its `why`; a file with no reason stops the run, so
// every edit carries one. The row is then re-applied to a copy of the before tree by
// apply.mjs, which checks it reproduces the after tree byte for byte.
import { readFileSync, readdirSync, statSync, writeFileSync, existsSync } from "node:fs";
import { join, relative, resolve, dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const KIT4 = resolve(HERE, "../../../../../../pass-4/B-kit");
const { hunksOf } = await import(pathToFileURL(join(KIT4, "lib/row.mjs")).href);

const args = process.argv.slice(2);
const arg = (k) => { const i = args.indexOf(k); if (i < 0) throw new Error(`missing ${k}`); return args[i + 1]; };
const before = resolve(arg("--before"));
const root = resolve(arg("--root"));
const out = resolve(arg("--out"));
const why = arg("--why");
const reasons = JSON.parse(readFileSync(resolve(arg("--reasons")), "utf8"));

const SKIP = new Set(["node_modules", "dist", "dist-demo", ".git", ".vite", "coverage"]);
function walk(base, dir = base, acc = new Set()) {
    for (const name of readdirSync(dir)) {
        if (SKIP.has(name) || (dir === base && name === "docs")) continue;
        const abs = join(dir, name);
        const st = statSync(abs, { throwIfNoEntry: false });
        if (!st) continue;
        if (st.isDirectory()) walk(base, abs, acc);
        else acc.add(relative(base, abs));
    }
    return acc;
}
const A = walk(before), B = walk(root);
const files = [...new Set([...A, ...B])].sort();
const edits = [];
const missing = [];
for (const f of files) {
    const a = A.has(f) ? readFileSync(join(before, f), "utf8") : null;
    const b = B.has(f) ? readFileSync(join(root, f), "utf8") : null;
    if (a === b) continue;
    const reason = reasons[f];
    if (!reason) { missing.push(f); continue; }
    if (a === null) edits.push({ file: f, why: reason, create: b });
    else if (b === null) edits.push({ file: f, why: reason, remove: true });
    else for (const [from, to] of hunksOf(a, b)) edits.push({ file: f, why: reason, from, to });
}
if (missing.length) { console.error(`no reason for:\n  ${missing.join("\n  ")}`); process.exit(1); }
const text = `// ${relative(resolve(HERE, ".."), out)} — AUTHORED input to pass-4's derive/edits.mjs (B-S11, zone src).
// Generated by tools/gen-row.mjs from the tree before and after the split; every edit
// carries its own why. Apply order: tools/apply.mjs (ORDER.json).
export const why = ${JSON.stringify(why)};

export const edits = ${JSON.stringify(edits, null, 1)};
`;
writeFileSync(out, text);
const tally = edits.reduce((t, e) => ((t[e.create !== undefined ? "create" : e.remove ? "remove" : "hunk"] += 1), t), { create: 0, remove: 0, hunk: 0 });
console.log(JSON.stringify({ out: relative(process.cwd(), out), files: new Set(edits.map((e) => e.file)).size, ...tally }));
if (!existsSync(out)) process.exit(1);
