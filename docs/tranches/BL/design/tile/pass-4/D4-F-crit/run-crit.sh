#!/bin/zsh
# D4-F pass-4 CRITIC seat driver. The prototype's run-proto.sh re-pointed at the critic's own worktree, out dir and
# logs (its patch, check and film stages removed: the patch is applied, not regenerated; G is owner-blocked and not
# re-filmed), plus the critic's own reads: crit-f.mjs on route-crit/ (the reactive flip, a pill group inside a tile
# option, plated, a wrapper write, a mixed set), the canon plants A, S, H and the D′ critic's two extra plants against
# the units, the critic's unit cases, and the nopin variant of the crit compositions.
# One stage per call; every log's first and last line carry the wall clock and the 1/5/15-min load. Every build, unit
# run and browser run goes through the machine guard (--light --rss-gb 8); every run that may start Playwright WebKit
# also holds --exclusive webkit, the whole WebKit stage in ONE hold. One heavy run at a time, serial.
# Do not edit this file while a stage runs.
#   run-crit.sh tsc | build | build-extra | unit | unit-plants | chromium | webkit | bundle
W=/Users/mkbabb/Programming/glass-ui/.claude/worktrees/bl/D4/p4/D4-F-crit
WT=$W/wt; O=$W/out; B=$O/builds
HN=/Users/mkbabb/Programming/glass-ui/docs/tranches/BL/design/tile/harness
P4=/Users/mkbabb/Programming/glass-ui/docs/tranches/BL/design/tile/pass-4
S=$P4/D4-F-crit; SP=$P4/D4-F-spec; FPR=$P4/D4-F-proto; F3=$P4/floor-v3; P3=$P4/../pass-3
L=$S/logs; R=$SP/route; RA=$HN/attack-route; RF=$SP/probes/route-f4; RC=$S/probes/route-crit
DPC=$P4/D4-Dp-crit/probes; PS=$P3/D4-Dp-spec/probes; FP3=$P3/D4-F-proto/probes
G=~/.claude/guard/guarded
mkdir -p $L $O
stamp() { echo "$(date '+%F %T') · load $(sysctl -n vm.loadavg)"; }
glog() {
  local name=$1; shift; local gopts=(); while [[ $1 != -- ]]; do gopts+=($1); shift; done; shift
  local F=$L/$name.log; stamp > $F
  $G --light --rss-gb 8 $gopts -- zsh -c 'echo "admitted · $(date "+%F %T") · load $(sysctl -n vm.loadavg)"; exec "$@"' _ "$@" >> $F 2>&1
  local rc=$?; echo "exit $rc · $(stamp)" >> $F; return $rc
}
log() { local F=$L/$1.log; shift; stamp > $F; "$@" >> $F 2>&1; local rc=$?; echo "exit $rc · $(stamp)" >> $F; }
SRC_W=(T-1:t1-corner-stops T-2:t2-one-line-stadium T-3:t3-selected-separates T-4:t4-ring-whole T-5:t5-one-of-n-keys T-6:t6-engagement T-7:t7-no-consumer-paint W-A:wa-curvature-content W-B:wb-choice-card W-C:wc-selection-behaviour W-D:wd-declared-cell W-E:we-one-line CANON:canon REPORT:report-h46)
ATK_W=(FACT:fact-split ATTACK:attack CORNER:corner-refusal)
SH=src/components/toggle-group/styles.css
TG=tests/components/ui/toggle-group/ToggleGroup.test.ts
RC_T=tests/styles/radius-role-canon.test.ts
CU=tests/components/ui/toggle-group/__crit_f.test.ts
variant() { # variant <name> <file> <old-file> <new-file> <builds...>
  local n=$1 f=$2 old=$3 new=$4; shift 4
  glog build-variant-$n --timeout 20 -- zsh -c "cd $WT && cp $f $f.orig && python3 -c 'import sys;p,o,n=sys.argv[1:];s=open(p).read();o=open(o).read();n=open(n).read();assert s.count(o)==1,\"anchor\";open(p,\"w\").write(s.replace(o,n))' $f $old $new && echo 'variant $n applied' && $* ; rc=\$?; mv $f.orig $f && echo 'variant $n restored'; exit \$rc"
}

reads() {
  local e=$1
  for w in $SRC_W; do log src-${w%%:*}-$e node $HN/${w#*:}.mjs --build $B/fc-src --out $O --engine $e; done
  for w in $ATK_W; do log atk-${w%%:*}-$e node $HN/${w#*:}.mjs --build $B/fc-atk-src --out $O --engine $e; done
  for w in t2-one-line-stadium t5-one-of-n-keys we-one-line; do log dist-$w-$e node $HN/$w.mjs --build $B/fc-dist --out $O --engine $e; done
  for w in fact-split attack corner-refusal; do log atkdist-$w-$e node $HN/$w.mjs --build $B/fc-atk-dist --out $O --engine $e; done
  log atkdev-attack-$e node $HN/attack.mjs --build $B/fc-atk-src-dev --out $O --engine $e
  # the critic's cells (src, src-dev, dist) and the pin's part in N3 (nopin)
  for f in src src-dev dist; do log critf-$f-$e node $S/probes/crit-f.mjs --build $B/fc-crit-$f --out $O --engine $e; done
  log critf-nopin-src-dev-$e node $S/probes/crit-f.mjs --build $B/fcv-nopin-crit-src-dev --out $O --engine $e
  # the route's own attack probe and its nopin variant
  for f in src src-dev dist; do log own-$f-$e node $SP/probes/f4-attack.mjs --build $B/fc-own-$f --out $O --engine $e; done
  log own-nopin-src-dev-$e node $SP/probes/f4-attack.mjs --build $B/fcv-nopin-own-src-dev --out $O --engine $e
  log selector-forms-$e node $SP/probes/selector-forms.mjs $e
  log canon-fact-$e node $SP/probes/canon-fact.mjs --build $B/fc-src --out $O --engine $e
  for p in a s h; do log canon-fact-plant-$p-$e node $SP/probes/canon-fact.mjs --build $B/fc-src --out $O --engine $e --plant $p; done
  # the D′ pass-4 critic's attack (the fact written on the item), and the prototype's flip (DOM edits)
  for b in fc-src fc-src-dev fc-dist; do log crit-level-$b-$e node $DPC/crit-level.mjs --build $B/$b --engine $e --out $O; done
  for b in fc-src fc-src-dev fc-dist; do log anatomy-flip-$b-$e node $FPR/probes/anatomy-flip.mjs --build $B/$b --engine $e --out $O; done
  # the carried rows, the shared pass-3 instruments
  for part in states hover ink a11y; do log carried-states-$part-$e node $PS/states.mjs --build $B/fc-src --part $part --engines $e; done
  log carried-states-hover-f1-$e node $PS/states.mjs --build $B/fc-src --part hover --sites f1-migrated --engines $e
  for part in x3 x6 tone; do log carried-crit-$part-$e node $PS/crit.mjs --build $B/fc-src --part $part --engines $e; done
  log carried-crit-desc-$e node $PS/crit.mjs --build $B/fc-src-dev --part desc --engines $e
  # the floor's probes on this build
  log probe-tile-geometry-$e node $F3/probes/tile-geometry.mjs --build $B/fc-src --engine $e --corner
  log probe-pill-row-$e node $F3/probes/pill-row.mjs --build $B/fc-src --engine $e
  log probe-corner-gap-$e node $P3/D4-Dp-proto/probes/corner-gap.mjs --build $B/fc-src --engines $e
  log probe-unmigrated-dist-$e node $P3/floor-v2/probes/unmigrated.mjs --build $B/fc-dist --engines $e
  log p3-forced-cost-$e node $FP3/p3.mjs --build $B/fc-src --engines $e --only forced,cost
  # R-3's plant: the kick deleted, T-6 must lose its commit cells
  log t6-pop0-$e node $HN/t6-engagement.mjs --build $B/fc-pop0-src --out $O/plant-pop0 --engine $e
}

case $1 in
  tsc)
    glog tsc-app --timeout 20 -- zsh -c "cd $WT && node node_modules/vue-tsc/bin/vue-tsc.js --noEmit"
    glog tsc-test --timeout 20 -- zsh -c "cd $WT && node node_modules/vue-tsc/bin/vue-tsc.js --noEmit -p tsconfig.test.json" ;;
  build)
    glog libbuild --timeout 20 -- node $HN/libbuild.mjs $WT
    for f in src src-dev dist dist-dev; do glog build-fc-$f --timeout 15 -- node $HN/build.mjs $WT --label fc-$f --out $O --flavor $f --route $R; done
    for f in src src-dev dist; do glog build-fc-atk-$f --timeout 15 -- node $HN/build.mjs $WT --label fc-atk-$f --out $O --flavor $f --route $RA; done
    for f in src src-dev dist; do glog build-fc-own-$f --timeout 15 -- node $HN/build.mjs $WT --label fc-own-$f --out $O --flavor $f --route $RF; done
    for f in src src-dev dist; do glog build-fc-crit-$f --timeout 15 -- node $HN/build.mjs $WT --label fc-crit-$f --out $O --flavor $f --route $RC; done ;;
  build-extra) # measurement-only: nopin (the route's own probe and the critic's), childwriter (the floor stub's writer), the kick plant
    variant nopin $SH $SP/probes/variants/pin.old $SP/probes/variants/pin.new \
      "node $HN/build.mjs $WT --label fcv-nopin-own-src-dev --out $O --flavor src-dev --route $RF && node $HN/build.mjs $WT --label fcv-nopin-crit-src-dev --out $O --flavor src-dev --route $RC"
    variant childwriter $SH $SP/probes/variants/writer.old $SP/probes/variants/writer.child \
      "node $HN/build.mjs $WT --label fcv-child-own-src --out $O --flavor src --route $RF && node $HN/build.mjs $WT --label fcv-child-src --out $O --flavor src --route $R"
    printf '%s' "animation: toggle-group-commit 450ms" > $O/pop0.old
    printf '%s' "animation: none 450ms" > $O/pop0.new
    variant pop0 $SH $O/pop0.old $O/pop0.new "node $HN/build.mjs $WT --label fc-pop0-src --out $O --flavor src --route $R" ;;
  unit)
    glog unit-all --timeout 40 -- node $HN/unit.mjs $WT --label fc-all --out $O
    glog unit-selftest --timeout 20 -- node $HN/unit.mjs $WT --selftest --out $O ;;
  unit-plants) # the route's four plants, the canon plants A, S, H, the D′ critic's two extra plants, the critic's cases
    P() { local n=$1; shift; glog unit-plant-$n --timeout 15 -- node $HN/unit.mjs $WT --label plant-$n --out $O "$@"; }
    IT=src/components/toggle-group/ToggleGroupItem.vue
    PIN="    :where(.toggle-group__item, .toggle-group__item *) {"
    SEL=".toggle-group:has(.toggle-group__item > :is(.toggle-group__media, .toggle-group__meta)) .toggle-group__item"
    TAIL="            background: HighlightText;
        }
    }
}"
    P clean-targets $TG $RC_T
    P rows-on-slot-function --sub "$IT|v-if=\"yields(\$slots.meta?.())\"|v-if=\"\$slots.meta\"" -t "a row renders only when" $TG
    P second-writer --sub "$SH|$PIN|    .toggle-group:has(.toggle-group__item > .toggle-group__meta) { --selection-tile: plated; }
$PIN" -t "one rule writes the tile fact" $TG
    P pin-not-important --sub "$SH|        --selection-tile: inherit !important;|        --selection-tile: inherit;" -t "one rule writes the tile fact" $TG
    P mark-off-fact --sub "$SH|            /* D4-F: the mark (below) */
            --toggle-group-marked: 1;|            /* D4-F: the mark (below) */" -t "one rule writes the tile fact" $TG
    # R-7: the canon plants on the route's own spelling (canon.mjs's plants(sel), route.json canon.sel), every unit file
    P canon-a --sub "$SH|$PIN|    :is($SEL) { border-radius: 12px; }
$PIN" $TG $RC_T
    P canon-s --sub "$SH|$PIN|    .toggle-group[data-size=\"sm\"] :is($SEL) { border-radius: var(--radius-panel); }
$PIN" $TG $RC_T
    P canon-h --sub "$SH|$PIN|    .toggle-group__item:has(> * + *) { border-radius: 12px; }
$PIN" $TG $RC_T
    # the D′ critic's two plants outside A, S, H (D4-Dp-critique.md §5.2), read on F's units
    P layer --sub "$SH|$TAIL|$TAIL
.toggle-group { --selection-tile: none; }" $TG $RC_T
    P foreign --sub "$SH|$PIN|    .pill-row.control-surface { border-radius: 12px; }
$PIN" $TG $RC_T
    P clean-after $TG $RC_T
    # the critic's cases: copied in, run, removed
    cp $S/probes/crit-units.test.ts $WT/$CU
    P crit-cases $CU
    rm -f $WT/$CU ;;
  chromium-inner) reads chromium
    log own-child-src-chromium node $SP/probes/f4-attack.mjs --build $B/fcv-child-own-src --out $O --engine chromium
    for w in t1-corner-stops t3-selected-separates; do log child-$w-chromium node $HN/$w.mjs --build $B/fcv-child-src --out $O --engine chromium; done ;;
  chromium)
    glog battery-src-chromium --timeout 90 -- node $HN/run.mjs --build $B/fc-src --attack $B/fc-atk-src --out $O --only T-1,T-2,T-3,T-4,T-5,T-6,T-7,W-A,W-B,W-C,W-D,W-E,CANON,FACT,ATTACK,CORNER,REPORT
    stamp > $L/chromium-all.log
    $G --light --rss-gb 8 --timeout 90 -- zsh $0 chromium-inner >> $L/chromium-all.log 2>&1
    echo "exit $? · $(stamp)" >> $L/chromium-all.log ;;
  webkit-inner)
    echo "admitted · $(stamp)"
    reads webkit
    log src-T-8-both node $HN/t8-both-engines.mjs --build $B/fc-src --out $O ;;
  webkit)
    stamp > $L/webkit-all.log
    $G --light --rss-gb 8 --exclusive webkit --timeout 90 -- zsh $0 webkit-inner >> $L/webkit-all.log 2>&1
    echo "exit $? · $(stamp)" >> $L/webkit-all.log ;;
  bundle)
    glog bundle --timeout 20 -- zsh $P3/floor-v2/probes/bundle.sh $WT "HEAD + floor v3 + D4-F pass-4 (critic re-read)" ;;
  *) echo "usage: see the header"; exit 2 ;;
esac
