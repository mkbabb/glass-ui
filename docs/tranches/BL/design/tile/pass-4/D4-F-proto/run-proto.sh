#!/bin/zsh
# D4-F pass-4 PROTOTYPE seat driver: the spec seat's run-f4.sh re-pointed (own worktree, own logs; the spec's route/,
# probes/ and route-f4/ read in place), plus what the spec left owed (D4-F-spec.md §8): the whole suite, the WebKit
# stage it could not run (T-4, T-6, W-A..W-E, CANON, the dist cells, REPORT on the route build), the carried rows re-read
# with the shared pass-3 instruments (X-1..X-7, R-4, R-5, FV-5), R-3's kick plant, the D′ pass-4 critic's crit-level
# attack, the :has() cost, the floor's probes on this build, the glance pair and the story page.
# One stage per call; every log's first and last line carry the wall clock and the 1/5/15-min load.
# Every build, unit run and browser run goes through the machine guard (--light --rss-gb 8, the path every pass-4 seat
# took); every run that may start Playwright WebKit also holds the machine-wide lock (--exclusive webkit), the whole
# WebKit stage in ONE hold. One heavy run at a time, serial. Do not edit this file while a stage runs.
#   run-proto.sh patch | check | tsc | build | build-extra | unit | unit-plants | chromium | webkit | bundle
W=/Users/mkbabb/Programming/glass-ui/.claude/worktrees/bl/D4/p4/D4-F-proto
WT=$W/wt; O=$W/out; B=$O/builds
HN=/Users/mkbabb/Programming/glass-ui/docs/tranches/BL/design/tile/harness
P4=/Users/mkbabb/Programming/glass-ui/docs/tranches/BL/design/tile/pass-4
S=$P4/D4-F-proto; SP=$P4/D4-F-spec; F3=$P4/floor-v3; P3=$P4/../pass-3
L=$S/logs; R=$SP/route; RA=$HN/attack-route; RF=$SP/probes/route-f4
DPC=$P4/D4-Dp-crit/probes; PS=$P3/D4-Dp-spec/probes; FP3=$P3/D4-F-proto/probes
G=~/.claude/guard/guarded
mkdir -p $L $O
stamp() { echo "$(date '+%F %T') · load $(sysctl -n vm.loadavg)"; }
glog() {
  local name=$1; shift; local gopts=(); while [[ $1 != -- ]]; do gopts+=($1); shift; done; shift
  local F=$L/$name.log; stamp > $F
  $G --light --rss-gb 8 $gopts -- zsh -c 'echo "admitted · $(date "+%F %T") · load $(sysctl -n vm.loadavg)"; exec "$@"' _ "$@" >> $F 2>&1
  local rc=$?; echo "exit $rc · $(stamp)" >> $F; return $rc
}
log() { local F=$L/$1.log; shift; stamp > $F; "$@" >> $F 2>&1; local rc=$?; echo "exit $rc · $(stamp)" >> $F; }
SRC_W=(T-1:t1-corner-stops T-2:t2-one-line-stadium T-3:t3-selected-separates T-4:t4-ring-whole T-5:t5-one-of-n-keys T-6:t6-engagement T-7:t7-no-consumer-paint W-A:wa-curvature-content W-B:wb-choice-card W-C:wc-selection-behaviour W-D:wd-declared-cell W-E:we-one-line CANON:canon REPORT:report-h46)
ATK_W=(FACT:fact-split ATTACK:attack CORNER:corner-refusal)
SH=src/components/toggle-group/styles.css; IT=src/components/toggle-group/ToggleGroupItem.vue
TG=tests/components/ui/toggle-group/ToggleGroup.test.ts
FILES=(src/components/toggle-group/ToggleGroupItem.vue src/components/toggle-group/styles.css tests/components/ui/toggle-group/ToggleGroup.test.ts MIGRATION.md demo/stories/forms/toggle.vue)
# a variant: one text substitution in the worktree for its builds, restored after (measurement only, never in the patch)
variant() { # variant <name> <file> <old-file> <new-file> <builds...>
  local n=$1 f=$2 old=$3 new=$4; shift 4
  glog build-variant-$n --timeout 20 -- zsh -c "cd $WT && cp $f $f.orig && python3 -c 'import sys;p,o,n=sys.argv[1:];s=open(p).read();o=open(o).read();n=open(n).read();assert s.count(o)==1,\"anchor\";open(p,\"w\").write(s.replace(o,n))' $f $old $new && echo 'variant $n applied' && $* ; rc=\$?; mv $f.orig $f && echo 'variant $n restored'; exit \$rc"
}

# every read that exists in both engines, for one engine ($1); the caller supplies the guard (and the WebKit lock)
reads() {
  local e=$1
  for w in $SRC_W; do log src-${w%%:*}-$e node $HN/${w#*:}.mjs --build $B/f4p-src --out $O --engine $e; done
  for w in $ATK_W; do log atk-${w%%:*}-$e node $HN/${w#*:}.mjs --build $B/f4p-atk-src --out $O --engine $e; done
  for w in t2-one-line-stadium t5-one-of-n-keys we-one-line; do log dist-$w-$e node $HN/$w.mjs --build $B/f4p-dist --out $O --engine $e; done
  for w in fact-split attack corner-refusal; do log atkdist-$w-$e node $HN/$w.mjs --build $B/f4p-atk-dist --out $O --engine $e; done
  log atkdev-attack-$e node $HN/attack.mjs --build $B/f4p-atk-src-dev --out $O --engine $e
  # the route's own attack probe and the two variants that evidence its choices
  for f in src src-dev dist; do log own-$f-$e node $SP/probes/f4-attack.mjs --build $B/f4p-own-$f --out $O --engine $e; done
  log own-nopin-src-dev-$e node $SP/probes/f4-attack.mjs --build $B/f4v-nopin-own-src-dev --out $O --engine $e
  log own-child-src-$e node $SP/probes/f4-attack.mjs --build $B/f4v-child-own-src --out $O --engine $e
  for w in t1-corner-stops t3-selected-separates; do log child-$w-$e node $HN/$w.mjs --build $B/f4v-child-src --out $O --engine $e; done
  log selector-forms-$e node $SP/probes/selector-forms.mjs $e
  # R-7 on the container-aware read (the harness CANON is F3-1-blind)
  log canon-fact-$e node $SP/probes/canon-fact.mjs --build $B/f4p-src --out $O --engine $e
  for p in a s h; do log canon-fact-plant-$p-$e node $SP/probes/canon-fact.mjs --build $B/f4p-src --out $O --engine $e --plant $p; done
  # the D′ pass-4 critic's attack (the fact written on the item; the flip cells are D′'s declaration, reported)
  for b in f4p-src f4p-src-dev f4p-dist; do log crit-level-$b-$e node $DPC/crit-level.mjs --build $B/$b --engine $e --out $O; done
  # the carried rows, re-read on this build with the shared pass-3 instruments (route-neutral: [data-*] selectors)
  for part in states hover ink a11y; do log carried-states-$part-$e node $PS/states.mjs --build $B/f4p-src --part $part --engines $e; done
  log carried-states-hover-f1-$e node $PS/states.mjs --build $B/f4p-src --part hover --sites f1-migrated --engines $e
  for part in x3 x6 tone; do log carried-crit-$part-$e node $PS/crit.mjs --build $B/f4p-src --part $part --engines $e; done
  log carried-crit-desc-$e node $PS/crit.mjs --build $B/f4p-src-dev --part desc --engines $e
  # the floor's probes on this build
  log probe-tile-geometry-$e node $F3/probes/tile-geometry.mjs --build $B/f4p-src --engine $e --corner
  log probe-pill-row-$e node $F3/probes/pill-row.mjs --build $B/f4p-src --engine $e
  log probe-corner-gap-$e node $P3/D4-Dp-proto/probes/corner-gap.mjs --build $B/f4p-src --engines $e
  log probe-unmigrated-dist-$e node $P3/floor-v2/probes/unmigrated.mjs --build $B/f4p-dist --engines $e
  # the mark under forced colours and the :has() cost (pass 3's p3.mjs, unchanged)
  log p3-forced-cost-$e node $FP3/p3.mjs --build $B/f4p-src --engines $e --only forced,cost
  # R-3's plant: the kick deleted, T-6 must lose its commit cells
  log t6-pop0-$e node $HN/t6-engagement.mjs --build $B/f4p-pop0-src --out $O/plant-pop0 --engine $e
  # the glance pair (H3-13), flush against plated, preset and specimen
  log film-pair-$e node $HN/film.mjs --pair --engines $e --arms flush=$B/f4p-src,plated=$B/f4pp-src --dest $S/glance-pair --scratch $O/film-scratch
  log film-pair-specimen-$e node $HN/film.mjs --pair --site specimen --engines $e --arms flush=$B/f4p-src,plated=$B/f4pp-src --dest $S/glance-pair --scratch $O/film-scratch
}

case $1 in
  patch) # the route's patch: each touched file diffed against its HEAD + floor v3 copy (base/), never the checkout
    out=$P4/D4-F-proto.patch; : > $out
    for f in $FILES; do diff -u --label a/$f --label b/$f $W/base/$f $WT/$f >> $out; done
    shasum $out ;;
  check) # git apply --check on a fresh HEAD + floor v3, then apply and compare every file with the prototype's
    C=$W/chkwt
    git -C /Users/mkbabb/Programming/glass-ui worktree add --detach $C 9219651ed >/dev/null 2>&1
    (cd $C && git apply $P4/floor-v3.patch && git apply --check $P4/D4-F-proto.patch && echo "check: clean on HEAD + floor v3" \
      && git apply $P4/D4-F-proto.patch && for f in $FILES; do cmp $C/$f $WT/$f && echo "same $f"; done)
    git -C /Users/mkbabb/Programming/glass-ui worktree remove --force $C ;;
  tsc)
    glog tsc-app --timeout 20 -- zsh -c "cd $WT && node node_modules/vue-tsc/bin/vue-tsc.js --noEmit"
    glog tsc-test --timeout 20 -- zsh -c "cd $WT && node node_modules/vue-tsc/bin/vue-tsc.js --noEmit -p tsconfig.test.json" ;;
  build)
    glog libbuild --timeout 20 -- node $HN/libbuild.mjs $WT
    for f in src src-dev dist dist-dev; do glog build-f4p-$f --timeout 15 -- node $HN/build.mjs $WT --label f4p-$f --out $O --flavor $f --route $R; done
    for f in src src-dev dist; do glog build-f4p-atk-$f --timeout 15 -- node $HN/build.mjs $WT --label f4p-atk-$f --out $O --flavor $f --route $RA; done
    for f in src src-dev dist; do glog build-f4p-own-$f --timeout 15 -- node $HN/build.mjs $WT --label f4p-own-$f --out $O --flavor $f --route $RF; done ;;
  build-extra) # measurement-only builds: the two variants, the plated arm (Q-2's pair), the kick plant (R-3)
    variant nopin $SH $SP/probes/variants/pin.old $SP/probes/variants/pin.new \
      "node $HN/build.mjs $WT --label f4v-nopin-own-src-dev --out $O --flavor src-dev --route $RF"
    variant childwriter $SH $SP/probes/variants/writer.old $SP/probes/variants/writer.child \
      "node $HN/build.mjs $WT --label f4v-child-own-src --out $O --flavor src --route $RF && node $HN/build.mjs $WT --label f4v-child-src --out $O --flavor src --route $R"
    printf '%s' "        --selection-tile: flush;
    }

    /* THE FACT IS THE GROUP'S" > $O/plated.old
    printf '%s' "        --selection-tile: plated;
    }

    /* THE FACT IS THE GROUP'S" > $O/plated.new
    variant plated $SH $O/plated.old $O/plated.new "node $HN/build.mjs $WT --label f4pp-src --out $O --flavor src --route $R"
    printf '%s' "animation: toggle-group-commit 450ms" > $O/pop0.old
    printf '%s' "animation: none 450ms" > $O/pop0.new
    variant pop0 $SH $O/pop0.old $O/pop0.new "node $HN/build.mjs $WT --label f4p-pop0-src --out $O --flavor src --route $R" ;;
  unit) # the whole suite through the one unit driver (H4-3), two workers; then the driver's own self-test
    glog unit-all --timeout 40 -- node $HN/unit.mjs $WT --label f4p-all --out $O
    glog unit-selftest --timeout 20 -- node $HN/unit.mjs $WT --selftest --out $O ;;
  unit-plants) # each route case against the mutation it exists to catch: every plant must exit 1, then clean again
    P() { local n=$1; shift; glog unit-plant-$n --timeout 15 -- node $HN/unit.mjs $WT --label plant-$n --out $O "$@"; }
    P clean-targets $TG
    P rows-on-slot-function --sub "$IT|v-if=\"yields(\$slots.meta?.())\"|v-if=\"\$slots.meta\"" -t "a row renders only when" $TG
    P second-writer --sub "$SH|    :where(.toggle-group__item, .toggle-group__item *) {|    .toggle-group:has(.toggle-group__item > .toggle-group__meta) { --selection-tile: plated; }
    :where(.toggle-group__item, .toggle-group__item *) {" -t "one rule writes the tile fact" $TG
    P pin-not-important --sub "$SH|        --selection-tile: inherit !important;|        --selection-tile: inherit;" -t "one rule writes the tile fact" $TG
    P mark-off-fact --sub "$SH|            /* D4-F: the mark (below) */
            --toggle-group-marked: 1;|            /* D4-F: the mark (below) */" -t "one rule writes the tile fact" $TG
    P clean-after $TG ;;
  chromium-inner) reads chromium
    log story-chromium node $S/probes/story.mjs $WT --engines chromium --shots $O/story --json $O/story-chromium.json ;;
  chromium) # the whole Chromium stage under one guard (no WebKit: Chromium only)
    glog battery-src-chromium --timeout 90 -- node $HN/run.mjs --build $B/f4p-src --attack $B/f4p-atk-src --out $O --only T-1,T-2,T-3,T-4,T-5,T-6,T-7,W-A,W-B,W-C,W-D,W-E,CANON,FACT,ATTACK,CORNER,REPORT
    stamp > $L/chromium-all.log
    $G --light --rss-gb 8 --timeout 90 -- zsh $0 chromium-inner >> $L/chromium-all.log 2>&1
    echo "exit $? · $(stamp)" >> $L/chromium-all.log ;;
  webkit-inner) # every Playwright WebKit read in ONE lock hold, then T-8 (one run over both engines)
    echo "admitted · $(stamp)"
    reads webkit
    log src-T-8-both node $HN/t8-both-engines.mjs --build $B/f4p-src --out $O ;;
  webkit)
    stamp > $L/webkit-all.log
    $G --light --rss-gb 8 --exclusive webkit --timeout 90 -- zsh $0 webkit-inner >> $L/webkit-all.log 2>&1
    echo "exit $? · $(stamp)" >> $L/webkit-all.log ;;
  bundle)
    glog bundle --timeout 20 -- zsh $P3/floor-v2/probes/bundle.sh $WT "HEAD + floor v3 + D4-F pass-4 proto" ;;
  *) echo "usage: see the header"; exit 2 ;;
esac
