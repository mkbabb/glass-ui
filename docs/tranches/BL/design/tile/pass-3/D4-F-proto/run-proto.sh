#!/bin/zsh
# D4-F pass-3 prototype · run-proto.sh · build and read HEAD + floor v2 + D4-F-proto.patch under H3.
# Serialized: every witness and probe takes the harness lock. Each log's first and last lines carry the load.
#   zsh run-proto.sh <worktree> <out root> <stage>
#   stage: build | check | uplants | bundle | battery | dist | probe | extra | shared | plants | pair | story | all
# Builds: f3p-{src,src-dev,dist,dist-dev} (the route, flush) and f3pp-src (the same source with the one value `plated`,
# restored after, for Q-2's pair). The route directory (route.json, migrated.mjs) is the spec's, unchanged (P-3).
# Sitting 2 (2026-10-14) re-runs every stage: sitting 1 (2026-10-13, logs in sitting-1/logs) built and checked at
# load 130-560 and its battery hung two witnesses at load 400-840.
# Sitting 3 (2026-10-15) re-runs every stage on the same patch (sha1 7313c674) after sitting 2 died mid-battery; each
# sitting's records go to their own directories: SIT=s3 writes logs-s3/, runs-s3/, shots-s3/, glance-pair-s3/ (sitting 2's
# partial logs/ and its r1 read in logs-r1/, runs-r1/ stay as they were).
# Do not edit this file while it runs: zsh reads a script as it executes it.
H=/Users/mkbabb/Programming/glass-ui/docs/tranches/BL/design/tile/harness
T=/Users/mkbabb/Programming/glass-ui/docs/tranches/BL/design/tile/pass-3
F=$T/D4-F-proto
S=$T/D4-F-spec
C=/Users/mkbabb/Programming/glass-ui/docs/tranches/BL/design/tile/pass-2/D4-F-crit/probes/crit.mjs
WT=$1; O=$2; ST=${3:-all}; X=${SIT:+-$SIT}; LG=$F/logs$X; RN=$F/runs$X; SH=$F/shots$X; GP=$F/glance-pair$X; mkdir -p $LG $RN $SH $GP
stamp() { echo "$(date '+%F %T') · load $(sysctl -n vm.loadavg)"; }
run() { L=$LG/$1.log; shift; stamp > $L; "$@" >> $L 2>&1; echo "exit $? · $(stamp)" >> $L; }
want() { [[ $ST == all || $ST == $1 ]]; }
CSS=$WT/src/components/toggle-group/styles.css
VT="node node_modules/vitest/vitest.mjs run --config vitest.wt.config.ts"
LANES="tests/components/ui/toggle-group/ToggleGroup.test.ts tests/components/custom/tabs/roving-grid.test.ts tests/components/fading-scroll.contract.test.ts tests/styles/radius-role-canon.test.ts tests/components/custom/tabs/segmented-tabs.test.ts tests/gates/tabs-seam.test.ts tests/styles/glass-subtlety.test.ts"

if want build; then
  run build-lib node $H/libbuild.mjs $WT
  for f in src src-dev dist dist-dev; do
    run build-$f node $H/build.mjs $WT --label f3p-$f --out $O --flavor $f --route $S/route
  done
  sed -i '' 's/--selection-tile: flush;/--selection-tile: plated;/' $CSS
  run build-plated node $H/build.mjs $WT --label f3pp-src --out $O --flavor src --route $S/route
  sed -i '' 's/--selection-tile: plated;/--selection-tile: flush;/' $CSS
  (cd $WT && shasum src/components/toggle-group/ToggleGroupItem.vue src/components/toggle-group/styles.css src/components/fading-scroll/FadingScroll.vue) > $LG/src-at-build.sha1
fi
if want check; then
  run wt-tsc-app zsh -c "cd $WT && node node_modules/vue-tsc/bin/vue-tsc.js --noEmit; echo vue-tsc app exit \$?"
  run wt-tsc-test zsh -c "cd $WT && node node_modules/vue-tsc/bin/vue-tsc.js --noEmit -p tsconfig.test.json; echo vue-tsc tests exit \$?"
  run wt-unit-all zsh -c "cd $WT && $VT"
  run wt-unit-lanes zsh -c "cd $WT && $VT $LANES"
  run wt-unit-route-gc zsh -c "cd $WT && NODE_OPTIONS=--expose-gc $VT tests/components/ui/toggle-group/ToggleGroup.test.ts tests/components/fading-scroll.contract.test.ts"
  for k in 1 2 3; do run wt-unit-all-repeat-$k zsh -c "cd $WT && $VT"; done
fi
if want uplants; then
  run wt-unit-plants bash $F/probes/unit-plants.sh $WT
fi
if want bundle; then
  run bundle zsh $T/floor-v2/probes/bundle.sh $WT "HEAD + floor v2 + D4-F-proto"
fi
if want battery; then
  run battery-src node $H/run.mjs --build $O/builds/f3p-src --out $O --webkit
fi
if want dist; then
  for e in chromium webkit; do for w in we-one-line t5-one-of-n-keys t2-one-line-stadium; do
    run battery-dist-$w-$e node $H/$w.mjs --build $O/builds/f3p-dist --out $O --engine $e
  done; done
fi
if want probe; then
  run probe-src node $S/probes/f3.mjs --build $O/builds/f3p-src --shots $SH --json $RN/probe-src.json
  run probe-rest-plated node $S/probes/f3.mjs --build $O/builds/f3pp-src --only rest --json $RN/probe-rest-plated.json
  for f in src-dev dist dist-dev; do
    run probe-unmig-$f node $S/probes/f3.mjs --build $O/builds/f3p-$f --only unmig --json $RN/probe-unmig-$f.json
  done
  run probe-p3 node $F/probes/p3.mjs --build $O/builds/f3p-src --json $RN/probe-p3.json
  run probe-p3-stack-src-dev node $F/probes/p3.mjs --build $O/builds/f3p-src-dev --only stack --json $RN/probe-p3-stack-src-dev.json
  run probe-p3-stack-dist-dev node $F/probes/p3.mjs --build $O/builds/f3p-dist-dev --only stack --json $RN/probe-p3-stack-dist-dev.json
  run probe-p3-stack-dist node $F/probes/p3.mjs --build $O/builds/f3p-dist --only stack --json $RN/probe-p3-stack-dist.json
fi
if want extra; then
  for f in src src-dev dist dist-dev; do
    run floor-names-$f node $T/floor-v2/probes/tile-fact.mjs --build $O/builds/f3p-$f --part names
  done
  run proto-probe-src node $T/../pass-2/D4-F-proto/probe.mjs --build $O/builds/f3p-src --only q2,q3,q5,hover,ink,double,contrast --json $RN/proto-probe-src.json
  run shared-crit-plants node $C --build $O/builds/f3p-src --part plants
fi
if want shared; then
  run shared-crit-tone node $C --build $O/builds/f3p-src --part tone
  run shared-crit-desc node $C --build $O/builds/f3p-src-dev --part desc
  run shared-crit-x3 node $C --build $O/builds/f3p-src --part x3
  run shared-crit-x6 node $C --build $O/builds/f3p-src --part x6
  run shared-crit-late-src-dev node $C --build $O/builds/f3p-src-dev --part late
  run shared-crit-late-dist-dev node $C --build $O/builds/f3p-dist-dev --part late
  run shared-crit-br-dist node $C --build $O/builds/f3p-dist --part br
fi
if want plants; then
  for pl in a s h; do for e in chromium webkit; do
    run canon-plant-$pl-$e node $H/canon.mjs --build $O/builds/f3p-src --plant $pl --engine $e
  done; done
fi
if want pair; then
  run film-pair node $H/film.mjs --pair --arms flush=$O/builds/f3p-src,plated=$O/builds/f3pp-src --dest $GP --scratch $O/film-scratch
  run film-pair-specimen node $H/film.mjs --pair --site specimen --arms flush=$O/builds/f3p-src,plated=$O/builds/f3pp-src --dest $GP --scratch $O/film-scratch
fi
if want story; then
  run story node $F/probes/story.mjs $WT --shots $SH/story --json $RN/story.json
fi
echo "done $ST $(stamp)" >> $LG/proto.done
