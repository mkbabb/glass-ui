#!/usr/bin/env node
// Emits the human-readable BH /api migration deliverable from the generated JSON.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
const OUT = dirname(fileURLToPath(import.meta.url));
const table = JSON.parse(readFileSync(resolve(OUT, "api-migration-table.json"), "utf8"));
const { summary, perSubpathDelta } = JSON.parse(readFileSync(resolve(OUT, "api-migration-summary.json"), "utf8"));

// group rows by owning subpath, sorted
const groups = {};
for (const r of table) (groups[r.owningSubpath] = groups[r.owningSubpath] || []).push(r);
const orderKeys = Object.keys(groups).sort((a, b) => {
    const ao = a.startsWith("(ORPHAN"), bo = b.startsWith("(ORPHAN");
    if (ao !== bo) return ao ? 1 : -1; // orphans last
    return a.localeCompare(b);
});

// the 3 orphan re-homes
const RH = summary.orphanRehomes;

// per-subpath NEW-EXPORT delta: every non-orphan symbol is ALREADY exported by
// its owning subpath barrel (api re-exports FROM that barrel) → pure import-path
// swap, ZERO new export. Only the 3 orphans need a barrel to ADD an export.
const newExportDeltas = {
    "/card": ["Surface  (NEW — re-home from ui/_shared; + surfaceClass/SurfaceTier if a consumer needs the resolver value)"],
    "/command": ["MenuItemVariants  (NEW — re-home from ui/_shared; + the menuItemVariants value)"],
    "/forms": ["ControlSize  (NEW — re-home from ui/_shared; + controlSizeClass)"],
};

let md = "";
md += "# BH /api FOLD — symbol→owning-subpath MIGRATION MAP (5.0.0)\n\n";
md += "Generated by `regen-api-migration.mjs` (read-only parse of `src/api/index.ts` + `src/api/types-extra.ts`).\n";
md += "The `./api` discovery subpath is FOLD-DELETED at 5.0.0; every symbol below re-homes onto its OWNING published subpath so consumers swap the import PATH with ZERO symbol loss.\n\n";

md += "## Summary\n\n";
md += `- **Total /api symbols: ${summary.totalApiSymbols}** (72 export blocks across the two files). The synthesis prose figure "~164" was a low estimate; the exact mechanical count is **${summary.totalApiSymbols}**.\n`;
md += `- By kind: **${summary.byKind.type} types + ${summary.byKind.const} consts** (the 4 consts — DEFAULT_AURORA_CONFIG / PAPER_WASH_GROUND / MAX_NUCLEI / MAX_STOPS — all → /aurora).\n`;
md += `- Owning subpaths: **${summary.subpathCount}** distinct (incl. the root \`.\` barrel for 3 alert/avatar/toggle Variants).\n`;
md += `- **Orphans (true no-home): ${summary.orphans.length}** — ${summary.orphans.join(", ")} (all from \`ui/_shared\`, which is on NEITHER a flat subpath NOR the root barrel).\n`;
md += `- Completeness: every symbol appears **exactly once** (${summary.completeness.everySymbolExactlyOnce}); every row **resolved-or-orphan** (${summary.completeness.everyRowResolvedOrOrphan}); duplicates **${summary.completeness.duplicates.length}**.\n\n`;

md += "### THE KEY MIGRATION FACT (zero new exports for 200 of 203)\n\n";
md += "Every non-orphan symbol is **already exported by its owning subpath barrel today** — `/api` re-exports each FROM that barrel's own dir/leaf. So the fold is a **pure consumer import-path swap** (`from \"@mkbabb/glass-ui/api\"` → `from \"@mkbabb/glass-ui/<subpath>\"`); the owning subpath needs **NO new export**. Only the **3 `_shared` orphans** require their re-home barrel to ADD an export.\n\n";

md += "## Symbols per owning subpath\n\n| owning subpath | count |\n|---|---|\n";
for (const [k, n] of Object.entries(summary.symbolsPerSubpath).sort((a, b) => b[1] - a[1])) md += `| \`${k}\` | ${n} |\n`;
md += "| `(ORPHAN → re-home)` | 3 |\n\n";

md += "## Orphan re-home decisions (the 3 `_shared` symbols)\n\n";
for (const [sym, d] of Object.entries(RH)) {
    md += `### \`${sym}\` → **${d.decision}**\n\n${d.rationale}\n\n`;
}

md += "## Per-subpath NEW-EXPORT deltas (what each barrel must ADD)\n\n";
md += "Only THREE barrels add an export (the orphan re-homes). Every other owning subpath already publishes its /api symbols — listed in the full table below as the consumer's new import target.\n\n";
md += "| barrel | NEW export to add | source |\n|---|---|---|\n";
md += "| `/card` (components/ui/card/index.ts) | `Surface` (+ `surfaceClass`, `SurfaceTier`) | re-export from `../_shared` |\n";
md += "| `/command` (components/ui/command/index.ts) | `MenuItemVariants` (+ `menuItemVariants`) | re-export from `../_shared` |\n";
md += "| `/forms` (src/forms.ts) | `ControlSize` (+ `controlSizeClass`) | re-export from `./components/ui/_shared` |\n\n";

md += "## Cross-repo consumer roster (the by-name asks before the break)\n\n";
md += "Live SOURCE `@mkbabb/glass-ui/api` imports across the sibling constellation (read-only grep, 2026-06-28):\n\n";
md += "| consumer | site | symbols | re-home → ask |\n|---|---|---|---|\n";
md += "| **muster** | `frontend/src/composables/useAuroraConfig.ts:47` | `DEFAULT_AURORA_CONFIG`, `AuroraConfig` | both → `/aurora`; ask: re-point `/api`→`/aurora` |\n";
md += "| **speedtest** | `src/features/speedtest/ui/PhaseTimeline.vue:52` | `TimelineSegment` | → `/timeline`; ask: re-point `/api`→`/timeline` |\n";
md += "| **speedtest** | `vite.config.mjs:1033` | (optimizeDeps/build reference) | re-point the build-config `/api` string to the new subpath set (or drop) |\n";
md += "| slides · value.js · fourier | — | (no live source import) | CLEAN — no ask |\n\n";
md += "muster's W3 wave-doc snippets also reference `/api` (docs, not source) — they update with muster's migration, not a code edit here (foreign-tree fence: the asks are by-name, glass-ui edits ZERO sibling tree).\n\n";

md += "## FULL 203-ROW TABLE (grouped by owning subpath)\n\n";
md += "| symbol | kind | /api source | owning subpath |\n|---|---|---|---|\n";
for (const k of orderKeys) {
    for (const r of groups[k].sort((a, b) => a.symbol.localeCompare(b.symbol))) {
        const home = k.startsWith("(ORPHAN") ? `**ORPHAN → ${RH[r.symbol]?.decision || "?"}**` : `\`${k}\``;
        md += `| \`${r.symbol}\` | ${r.kind} | \`${r.source}\` | ${home} |\n`;
    }
}
md += "\n";

writeFileSync(resolve(OUT, "API-MIGRATION-MAP.md"), md);
console.log("wrote API-MIGRATION-MAP.md (", table.length, "rows )");
